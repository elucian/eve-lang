"""spec/spec.json: the machine index of the specification.

A program (or an AI that searches) reads this one file to find a rule without opening the pages: every page with
its title, status, summary, size and the sections (depth, anchor, line, title), so that a section can be read
with an offset and a limit; the data files; and the feature files. Rebuilt by `evegen index`; it never holds
anything that is not in the pages.
"""
import json
import re

import model
from model import ROOT, read_text, slug

SKIP_PAGES = ("features/",)
SKIP_DATA = ("features/", "schema/", "spec.json")


def page_entry(root, path):
    rel = path.relative_to(root / "spec").as_posix()
    text = read_text(path)
    lines = text.split("\n")
    title, status, summary, sections, fence = rel, "", "", [], False
    seen = {}
    for n, ln in enumerate(lines, 1):
        if ln.lstrip().startswith("```"):
            fence = not fence
            continue
        if fence:
            continue
        m = re.match(r"(#{1,4}) (.+?)\s*$", ln)
        if m:
            depth, heading = len(m.group(1)), m.group(2)
            if depth == 1 and title == rel:
                title = heading
                continue
            a = slug(heading)
            seen[a] = seen.get(a, 0) + 1
            if seen[a] > 1:
                a += "-%d" % (seen[a] - 1)
            sections.append([depth, a, n, heading])
            continue
        s = re.match(r"Status:\s*\*\*([^*]+)\*\*", ln)
        if s and not status:
            status = s.group(1).strip()
            continue
        if not summary and ln.strip() and not ln.startswith(("|", ">", "-", "License:", "Status:", "<")) and title != rel:
            summary = re.sub(r"[`*]", "", ln.strip())[:200]
    return {"path": rel, "title": title, "status": status, "summary": summary, "lines": len(lines),
            "bytes": len(text.encode("utf-8")), "sections": sections}


def data_entry(root, path):
    rel = path.relative_to(root / "spec").as_posix()
    d = model.jload(path)
    return {"path": rel, "id": path.stem, "items": len(d["items"]) if isinstance(d, dict) and "items" in d else None}


def build(root=ROOT):
    spec = root / "spec"
    pages = [page_entry(root, p) for p in sorted(spec.rglob("*.md"))
             if not p.relative_to(spec).as_posix().startswith(SKIP_PAGES)]
    data = [data_entry(root, p) for p in sorted(spec.rglob("*.json"))
            if not p.relative_to(spec).as_posix().startswith(SKIP_DATA)]
    levels = model.load_levels(root)
    feats = [{"path": "features/%s.json" % lv["id"], "id": lv["id"], "name": lv["name"],
              "features": [f["id"] for f in lv["features"]]} for lv in levels]
    refs = {}
    for lv in levels:
        for f in lv["features"]:
            for r in f.get("spec", []):
                refs.setdefault(r.split("#")[0], set()).add(f["id"])
    for p in pages:
        p["features"] = sorted(refs.get(p["path"], []), key=model.feature_key)
    return {"note": "Generated by `evegen index`; do not edit. sections: [depth, anchor, line, title].",
            "pages": pages, "data": data, "featureFiles": feats}


def dumps(index):
    out = ['{', ' "$schema": "schema/spec.schema.json",', ' "note": %s,' % json.dumps(index["note"], ensure_ascii=False), ' "pages": [']
    pages = []
    for p in index["pages"]:
        head = {k: v for k, v in p.items() if k != "sections"}
        body = json.dumps(head, ensure_ascii=False)[:-1]
        secs = ",\n".join("    " + json.dumps(s, ensure_ascii=False) for s in p["sections"])
        pages.append("  " + body + ', "sections": [' + ("\n" + secs + "\n   ]" if secs else "]") + "}")
    out.append(",\n".join(pages))
    out.append(" ],")
    out.append(' "data": [\n' + ",\n".join("  " + json.dumps(d, ensure_ascii=False) for d in index["data"]) + "\n ],")
    out.append(' "featureFiles": [\n' + ",\n".join("  " + json.dumps(d, ensure_ascii=False) for d in index["featureFiles"]) + "\n ]")
    out.append("}")
    return "\n".join(out) + "\n"


def run(root=ROOT, check=False):
    """-> True when spec/spec.json is up to date (and written, unless check)."""
    path = root / "spec" / "spec.json"
    text = dumps(build(root))
    same = path.is_file() and read_text(path) == text
    if not same and not check:
        model.write_text(path, text)
    return same
