#!/usr/bin/env python3
"""Generate evevm/src/nfc_data.zig, the tables of Unicode normalization form C (NFC), from the Unicode
data of the Python that runs this script (module unicodedata).

usage: python script/gen_nfc.py

NFC = canonical decomposition (NFD), reordering of the combining marks by their combining class, then canonical
composition. The Zig file holds three sorted tables so the VM finds an entry by binary search:
  decomp   code point -> its canonical decomposition (one step, 1 or 2 code points)
  ccc      code point -> canonical combining class (only the non-zero ones)
  compose  (first, second) -> composed code point (the primary composites: no exclusions)
Hangul syllables are not in the tables: the VM computes them (Unicode 3.12).
"""
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "evevm", "src", "nfc_data.zig")


def main():
    decomp = []
    ccc = []
    compose = []
    excluded = set()
    # composition exclusions: a character whose canonical decomposition is not used to compose
    for cp in range(0x110000):
        ch = chr(cp)
        c = unicodedata.combining(ch)
        if c:
            ccc.append((cp, c))
        d = unicodedata.decomposition(ch)
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        decomp.append((cp, parts))
        # a primary composite: decomposes to two, and NFC(composite) == composite (so it is not excluded)
        if len(parts) == 2 and unicodedata.normalize("NFC", ch) == ch:
            compose.append((parts[0], parts[1], cp))
    decomp.sort()
    ccc.sort()
    compose.sort()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("//! Tables of Unicode normalization form C. GENERATED by script/gen_nfc.py from Unicode %s: do not edit.\n" % unicodedata.unidata_version)
        f.write("//! Used by nfc.zig.\n\n")
        f.write("pub const Decomp = struct { cp: u21, a: u21, b: u21 }; // b is 0 when the decomposition has one code point\n\n")
        f.write("pub const decomp = [_]Decomp{\n")
        for cp, parts in decomp:
            # the table holds one step of the decomposition; nfc.zig applies it again until nothing changes
            a = parts[0]
            b = parts[1] if len(parts) > 1 else 0
            f.write("    .{ .cp = 0x%X, .a = 0x%X, .b = 0x%X },\n" % (cp, a, b))
        f.write("};\n\n")
        f.write("pub const Ccc = struct { cp: u21, class: u8 };\n\n")
        f.write("pub const ccc = [_]Ccc{\n")
        for cp, c in ccc:
            f.write("    .{ .cp = 0x%X, .class = %d },\n" % (cp, c))
        f.write("};\n\n")
        f.write("pub const Compose = struct { a: u21, b: u21, cp: u21 };\n\n")
        f.write("pub const compose = [_]Compose{\n")
        for a, b, cp in compose:
            f.write("    .{ .a = 0x%X, .b = 0x%X, .cp = 0x%X },\n" % (a, b, cp))
        f.write("};\n")
    print("decomp %d, ccc %d, compose %d -> %s" % (len(decomp), len(ccc), len(compose), os.path.relpath(OUT)))


if __name__ == "__main__":
    sys.exit(main())
