"""Writes code/evecm/src/ide/keywords.zig from spec/lexical/keywords.json (the colors of the editor).

Run from the repository root:  python code/evetx/gen_keywords.py
"""
import json

SPEC = 'spec/lexical/keywords.json'
OUT = 'code/evecm/src/ide/keywords.zig'

items = json.load(open(SPEC, encoding='utf-8'))['items']
# print, write and read are statements of the parser but not words of keywords.json (D-086: library functions)
EXTRA = ['print', 'read', 'write']
words = sorted({x['id'] for x in items if x['id'].isalpha()} | set(EXTRA))
lines = [
    '//! @eve-module ide.keywords',
    '//! @spec spec/lexical/keywords.json',
    '//! @decision D-193',
    '//! The keywords of Eve, for the colors of the editor.',
    '//!',
    '//! GENERATED by code/evetx/gen_keywords.py from spec/lexical/keywords.json: do not edit by hand.',
    '',
    '// Zig tip: a `const` array of string slices is fixed at compile time and lives in the program',
    '// image; `[_][]const u8{ ... }` lets the compiler count the entries.',
    'pub const words = [_][]const u8{',
]
lines += [f'    "{w}",' for w in words]
lines += ['};', '']
open(OUT, 'w', encoding='utf-8', newline='').write('\n'.join(lines))
print(len(words), 'keywords written to', OUT)
