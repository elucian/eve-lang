#!/usr/bin/env python3
"""Writes the Tree-sitter grammar of Eve and the highlight queries of the Zed extension from the specification.

Run from the repository root:  python tools/zed-eve/gen_zed.py
Then, to make the parser (needs the tree-sitter CLI, `npm i -g tree-sitter-cli`, or `npx tree-sitter-cli`):
    cd tools/tree-sitter-eve && tree-sitter generate

Sources: spec/lexical/keywords.json (the words, classified by script/genkeywords.py) and the list of types below.
Written files (generated, do not edit): tools/tree-sitter-eve/grammar.js, tools/tree-sitter-eve/queries/highlights.scm,
tools/zed-eve/languages/eve/highlights.scm.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT / "script"))
import genkeywords  # noqa: E402

# the words that the parser reserves but keywords.json does not list (print, read, write are library statements, D-086)
EXTRA_KEYWORDS = ["print", "read", "write"]
# built-in types and traits (spec/semantics/types.md, spec/library/); a capitalized name that is not here is still a type
TYPES = """Byte Short Integer Natural Huge Real Float Decimal Rational String Text Symbol Logic Table Rune Record Ordinal
Variant Date Time Instant Duration Array List Object Class Lambda Function DataSet DataMap HashMap Folder File Type
Secret Channel Memory Stream Iterable Comparable Printable Bytes Connection Atomic Error Warning""".split()
CONSTANTS = ["True", "False", "Null", "null"]


def words(names):
    return ", ".join(f"'{w}'" for w in sorted(set(names)))


GRAMMAR = r'''// GENERATED by tools/zed-eve/gen_zed.py from spec/lexical/keywords.json: do not edit by hand.
// A grammar for colors, not for the language: it reads a file as a list of tokens. The real parser is evecp.
module.exports = grammar({
  name: 'eve',

  extras: $ => [/\s+/],

  word: $ => $.identifier,

  rules: {
    source_file: $ => repeat($._token),

    _token: $ => choice(
      $.title,
      $.comment,
      $.comment_expr,
      $.comment_block,
      $.string,
      $.symbol,
      $.number,
      $.system_variable,
      $.reference,
      $.constant,
      $.keyword,
      $.control,
      $.operator_word,
      $.type,
      $.identifier,
      $.operator,
      $.bracket,
      $.punctuation,
    ),

    // `#` and `##` at the start of a line are the title and the subtitle; the grammar takes `#` anywhere (no column test)
    title: $ => token(prec(2, /#[^\n]*/)),

    // `**` to the end of the line
    comment: $ => token(prec(3, /\*\*[^\n]*/)),

    // `(** ... **)` and `/* ... */` may span lines; no nesting
    comment_expr: $ => token(prec(3, /\(\*\*([^*]|\*[^*]|\*\*[^)])*\*\*\)/)),
    comment_block: $ => token(prec(3, /\/\*([^*]|\*+[^*\/])*\*+\//)),

    // "text" with escapes, and the text literal """ ... """
    string: $ => token(choice(
      /"""([^"]|"[^"]|""[^"])*"""/,
      /"([^"@BS2@@BS@n]|@BS2@.)*"/,
    )),

    // 'a' and U+03B2
    symbol: $ => token(choice(/'([^'@BS2@@BS@n]|@BS2@.)*'/, /U\+[0-9A-Fa-f]+/)),

    number: $ => token(choice(
      /0[xX][0-9a-fA-F_]+/,
      /0[bB][01_]+/,
      /[0-9][0-9_]*(\.[0-9][0-9_]*)?([eE][+-]?[0-9]+)?[dD]?/,
    )),

    // $error, $err_sql
    system_variable: $ => /\$[A-Za-z_][A-Za-z0-9_]*/,

    // @self, @result
    reference: $ => /@[A-Za-z_][A-Za-z0-9_]*/,

    constant: $ => choice(@CONSTANTS@),

    keyword: $ => choice(@KEYWORDS@),

    control: $ => choice(@CONTROL@),

    operator_word: $ => choice(@OPERATORS@),

    type: $ => choice(@TYPES@, /[A-Z][A-Za-z0-9_]*/),

    // a name; `name!` marks a function that gives another value at each call
    identifier: $ => /[a-z_][A-Za-z0-9_]*!?/,

    operator: $ => token(choice(
      '..<', '>..<', '...', '..', '><', '=~', '!~', ':=', '==', '<>', '=>', '<:', ':>', '<-', '->', '<+', '+>',
      '<=', '>=', '&&', '||', '+=', '-=', '*=', '/=', '%=', '^=',
      /[-+*\/^%&|<>=!?:~]/,
    )),

    bracket: $ => /[()\[\]{}]/,

    punctuation: $ => /[;,.]/,
  },
});
'''


def grammar_js(groups):
    keyword = groups["keyword"] + EXTRA_KEYWORDS + groups["opening"]
    bs = chr(92)
    return (GRAMMAR.replace("@BS2@", bs * 2).replace("@BS@", bs).replace("@CONSTANTS@", words(CONSTANTS)).replace("@KEYWORDS@", words(keyword))
            .replace("@CONTROL@", words(groups["control"] + groups["constant"]))
            .replace("@OPERATORS@", words(groups["operator"])).replace("@TYPES@", words(TYPES)))


def highlights():
    return """; GENERATED by tools/zed-eve/gen_zed.py: do not edit by hand.
(title) @title
(comment) @comment
(comment_expr) @comment
(comment_block) @comment
(string) @string
(symbol) @string.special
(number) @number
(system_variable) @variable.special
(reference) @variable.special
(constant) @constant
(keyword) @keyword
(control) @keyword
(operator_word) @operator
(type) @type
(operator) @operator
(bracket) @punctuation.bracket
(punctuation) @punctuation.delimiter
(identifier) @variable
"""


def main():
    groups = genkeywords.classify()
    grammar = ROOT / "tools" / "tree-sitter-eve" / "grammar.js"
    grammar.write_text(grammar_js(groups), encoding="utf-8", newline="\n")
    for target in (ROOT / "tools" / "tree-sitter-eve" / "queries" / "highlights.scm",
                   ROOT / "tools" / "zed-eve" / "languages" / "eve" / "highlights.scm"):
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(highlights(), encoding="utf-8", newline="\n")
    print("grammar and highlights written;", sum(len(v) for v in groups.values()) + len(EXTRA_KEYWORDS), "words")


if __name__ == "__main__":
    main()
